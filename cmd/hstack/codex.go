package main

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/shellhaki/hstack"
)

// codexMarker is the first line of every TOML agent hstack writes. Only files that start with it
// are ours: install overwrites them, uninstall removes them, anything else is left alone.
const codexMarker = "# generated by hstack — do not edit; reinstall to update"

// codexHome is Codex's config directory: $CODEX_HOME if set, else ~/.codex.
func codexHome() string {
	if d := os.Getenv("CODEX_HOME"); d != "" {
		return d
	}
	return filepath.Join(home(), ".codex")
}

func codexAgentsDir() string { return filepath.Join(codexHome(), "agents") }

// renderCodexAgent turns one agents/*.md file (frontmatter plus body) into the TOML file Codex
// reads as a custom agent. It returns the Codex agent name (frontmatter name, "-" replaced by "_").
func renderCodexAgent(src string) (name string, out string, err error) {
	src = strings.ReplaceAll(src, "\r\n", "\n")
	rest, ok := strings.CutPrefix(src, "---\n")
	if !ok {
		return "", "", fmt.Errorf("no frontmatter")
	}
	front, body, ok := strings.Cut(rest, "\n---\n")
	if !ok {
		return "", "", fmt.Errorf("unterminated frontmatter")
	}
	fields := map[string]string{}
	for _, line := range strings.Split(front, "\n") {
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			continue
		}
		fields[strings.TrimSpace(k)] = unquote(strings.TrimSpace(v))
	}
	name = strings.ReplaceAll(fields["name"], "-", "_")
	if name == "" || fields["description"] == "" {
		return "", "", fmt.Errorf("frontmatter needs name and description")
	}
	body = strings.TrimRight(strings.TrimLeft(body, "\n"), " \t\n")

	var b strings.Builder
	b.WriteString(codexMarker + "\n")
	fmt.Fprintf(&b, "name = %s\n", tomlBasic(name))
	fmt.Fprintf(&b, "description = %s\n", tomlBasic(fields["description"]))
	fmt.Fprintf(&b, "developer_instructions = %s\n", tomlText(body))
	return name, b.String(), nil
}

// unquote strips one pair of matching double or single quotes around a frontmatter value.
func unquote(v string) string {
	if len(v) >= 2 && (v[0] == '"' || v[0] == '\'') && v[len(v)-1] == v[0] {
		return v[1 : len(v)-1]
	}
	return v
}

// tomlBasic writes s as a one-line TOML basic string with every special character escaped.
func tomlBasic(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// tomlText writes a long body as a multi-line literal string, which needs no escaping.
// If the body contains a triple single quote or a control character a literal string can't hold,
// it falls back to a basic string.
func tomlText(s string) string {
	if strings.Contains(s, "'''") {
		return tomlBasic(s)
	}
	for _, r := range s {
		if (r < 0x20 && r != '\n' && r != '\t') || r == 0x7f {
			return tomlBasic(s)
		}
	}
	return "'''\n" + s + "\n'''"
}

// isHstackTOML reports whether a file was written by hstack (its first line is the marker).
func isHstackTOML(b []byte) bool {
	first, _, _ := strings.Cut(string(b), "\n")
	return strings.TrimSpace(first) == codexMarker
}

// installCodexAgents writes one TOML file per embedded agents/*.md into the Codex agents dir and
// removes hstack's files whose agent no longer exists.
func installCodexAgents() error {
	dir := codexAgentsDir()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	entries, err := fs.ReadDir(hstack.Assets, "agents")
	if err != nil {
		return err
	}
	want := map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		src, err := hstack.Assets.ReadFile("agents/" + e.Name())
		if err != nil {
			return err
		}
		name, out, err := renderCodexAgent(string(src))
		if err != nil {
			return fmt.Errorf("agents/%s: %w", e.Name(), err)
		}
		file := strings.TrimSuffix(e.Name(), ".md") + ".toml"
		want[file] = true
		p := filepath.Join(dir, file)
		if old, err := os.ReadFile(p); err == nil && !isHstackTOML(old) {
			fmt.Printf("  skip %s: exists and is not an hstack file\n", p)
			continue
		}
		if err := os.WriteFile(p, []byte(out), 0o644); err != nil {
			return err
		}
		fmt.Printf("  %s %s (%s)\n", dim("wrote"), p, name)
	}
	for _, p := range hstackTOMLFiles(dir) {
		if !want[filepath.Base(p)] {
			if err := os.Remove(p); err != nil {
				return err
			}
			fmt.Printf("  %s %s\n", dim("removed"), p)
		}
	}
	return nil
}

// removeCodexAgents deletes every hstack-written TOML file in the Codex agents dir.
func removeCodexAgents() {
	for _, p := range hstackTOMLFiles(codexAgentsDir()) {
		if err := os.Remove(p); err == nil {
			fmt.Println("  removed", p)
		}
	}
}

// hstackTOMLFiles lists the marked hstack TOML files in dir.
func hstackTOMLFiles(dir string) []string {
	var out []string
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".toml") {
			continue
		}
		p := filepath.Join(dir, e.Name())
		if b, err := os.ReadFile(p); err == nil && isHstackTOML(b) {
			out = append(out, p)
		}
	}
	return out
}
