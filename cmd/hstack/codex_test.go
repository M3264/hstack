func TestInstallCodexAgentsSkipsForeignFilesAndRemovesStale(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("CODEX_HOME", dir)
	agents := filepath.Join(dir, "agents")
	if err := os.MkdirAll(agents, 0o755); err != nil {
		t.Fatal(err)
	}
	foreign := filepath.Join(agents, "hstack-worker.toml")
	if err := os.WriteFile(foreign, []byte("name = \"mine\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	stale := filepath.Join(agents, "hstack-gone.toml")
	if err := os.WriteFile(stale, []byte(codexMarker+"\nname = \"gone\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := installCodexAgents(); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(foreign); string(b) != "name = \"mine\"\n" {
		t.Fatalf("foreign file was overwritten: %s", b)
	}
	for _, f := range []string{"hstack-reviewer.toml", "hstack-researcher.toml"} {
		b, err := os.ReadFile(filepath.Join(agents, f))
		if err != nil || !isHstackTOML(b) {
			t.Fatalf("%s not written: %v", f, err)
		}
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatal("stale hstack file was not removed")
	}

	removeCodexAgents()
	if _, err := os.Stat(filepath.Join(agents, "hstack-reviewer.toml")); !os.IsNotExist(err) {
		t.Fatal("uninstall did not remove hstack file")
	}
	if _, err := os.Stat(foreign); err != nil {
		t.Fatal("uninstall removed a file that is not ours")
	}
}
