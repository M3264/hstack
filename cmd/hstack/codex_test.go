func TestRenderCodexAgentExact(t *testing.T) {
	src := "---\nname: hstack-worker\ndescription: hstack worker. Started by the hstack skill.\n---\nYou are a worker.\nLine two.\n"
	name, out, err := renderCodexAgent(src)
	if err != nil {
		t.Fatal(err)
	}
	if name != "hstack_worker" {
		t.Fatalf("name = %q", name)
	}
	want := "# generated by hstack — do not edit; reinstall to update\n" +
		"name = \"hstack_worker\"\n" +
		"description = \"hstack worker. Started by the hstack skill.\"\n" +
		"developer_instructions = '''\n" +
		"You are a worker.\nLine two.\n'''\n"
	if out != want {
		t.Fatalf("got:\n%s\nwant:\n%s", out, want)
	}
	if strings.Contains(out, "model") {
		t.Fatal("generated agent must not set a model key")
	}
}

func TestRenderCodexAgentLiteralKeepsBackslashAndQuotes(t *testing.T) {
	src := "---\nname: x-y\ndescription: \"He said \\\"go\\\"\"\n---\nSay \"hi\" and C:\\tmp\n"
	_, out, err := renderCodexAgent(src)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out, "developer_instructions = '''\nSay \"hi\" and C:\\tmp\n'''\n") {
		t.Fatalf("literal body not kept verbatim:\n%s", out)
	}
}

func TestRenderCodexAgentEscapesWhenBodyHasTripleQuote(t *testing.T) {
	// Body contains ''' so it must be a basic string with every special character escaped.
	body := "Use '''x''' here.\nPath C:\\tmp \t\"q\""
	src := "---\nname: a-b\ndescription: d\n---\n" + body + "\n"
	_, out, err := renderCodexAgent(src)
	if err != nil {
		t.Fatal(err)
	}
	want := `developer_instructions = "Use '''x''' here.\nPath C:\\tmp \t\"q\""` + "\n"
	if !strings.HasSuffix(out, want) {
		t.Fatalf("got:\n%s\nwant suffix:\n%s", out, want)
	}
}

func TestRenderCodexAgentEscapesControlCharacters(t *testing.T) {
	src := "---\nname: a\ndescription: d\n---\na\x01b\x7f\n"
	_, out, err := renderCodexAgent(src)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasSuffix(out, `developer_instructions = "a\u0001b\u007F"`+"\n") {
		t.Fatalf("control characters not escaped:\n%s", out)
	}
}

func TestRenderCodexAgentRejectsMissingFields(t *testing.T) {
	for _, src := range []string{
		"no frontmatter\n",
		"---\nname: a\n",
		"---\nname: a\n---\nbody\n",
	} {
		if _, _, err := renderCodexAgent(src); err == nil {
			t.Fatalf("expected error for %q", src)
		}
	}
}

